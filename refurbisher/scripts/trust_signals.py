    # ---- mechanical tier
    young = young_flag or (age is not None and age < 730)
    dl = ((pkg or {}).get("downloads") or 0) if (pkg or {}).get("downloads_period") == "last-month" else 0
    adoption_a = (deps or 0) >= 1000 or dl >= 1_000_000 or (not pkg and stars >= 5000)
