# ---------------------------------------------------------------- HTTP helpers
def _token() -> str | None:
    for key in ("GITHUB_TOKEN", "GH_TOKEN"):
        if os.environ.get(key):
            return os.environ[key]
    try:
        out = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True, timeout=5)
        return out.stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        return None


TOKEN = _token()


def http(url: str, data: dict | None = None, headers: dict | None = None):
    """Return (status, headers, parsed_json_or_text). status 0 means a network error."""
    hdrs = {"User-Agent": UA, "Accept": "application/json"}
    hdrs.update(headers or {})
    body = None
    if data is not None:
        body = json.dumps(data).encode()
        hdrs["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=body, headers=hdrs)
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
            raw = resp.read().decode("utf-8", "replace")
            status, rh = resp.status, dict(resp.headers)
    except urllib.error.HTTPError as e:
        raw = e.read().decode("utf-8", "replace") if e.fp else ""
        status, rh = e.code, dict(e.headers or {})
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        return 0, {}, str(e)
    try:
        return status, rh, json.loads(raw) if raw else None
    except json.JSONDecodeError:
        return status, rh, raw


def gh(path: str):
    headers = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    if TOKEN:
        headers["Authorization"] = f"Bearer {TOKEN}"
    with GH_SEM:
        return http(f"https://api.github.com/{path.lstrip('/')}", headers=headers)


PR_QUERY = """query($owner: String!, $name: String!) { repository(owner: $owner, name: $name) {
  merged: pullRequests(states: MERGED) { totalCount }
  recent: pullRequests(states: MERGED, last: 30) { nodes {
    authorAssociation author { login __typename } reviews(states: APPROVED) { totalCount } } } } }"""


def gql(query: str, variables: dict):
    if not TOKEN:  # GitHub GraphQL has no anonymous access
        return 0, {}, None
    with GH_SEM:
        return http("https://api.github.com/graphql", data={"query": query, "variables": variables},
                    headers={"Authorization": f"Bearer {TOKEN}"})


def last_page(headers: dict) -> int | None:
    link = headers.get("Link") or headers.get("link") or ""
    m = re.search(r'[?&]page=(\d+)>; rel="last"', link)
    return int(m.group(1)) if m else None


def q(s: str) -> str:
    return urllib.parse.quote(s, safe="")


def age_days(ts: str | None) -> float | None:
    if not ts:
        return None
    try:
        return (NOW - datetime.fromisoformat(ts.replace("Z", "+00:00"))).total_seconds() / 86400
    except ValueError:
        return None


# ---------------------------------------------------------------- target parsing
def parse_target(raw: str) -> dict:
    t = {"raw": raw, "repo": None, "package": None, "snippet": None, "host": "github.com", "error": None}
    for part in filter(None, (x.strip() for x in raw.split("+"))):
        head = part.split(":", 1)[0].lower()
        if "://" not in part and not part.startswith("git@") and ":" in part and "/" not in head:
            if head not in ECO:
                t["error"] = f"unknown ecosystem '{head}' (known: {', '.join(sorted(ECO))})"
                return t
            t["package"] = (head, part.split(":", 1)[1])
            continue
        s = re.sub(r"^(https?://|git@)", "", part).rstrip("/")
        s = re.sub(r"^([^/:]+):", r"\1/", s) if part.startswith("git@") else s
        s = re.sub(r"\.git$", "", s)
        host = "github.com"
        if "/" in s and "." in s.split("/", 1)[0]:
            host, s = s.split("/", 1)
        host = host.lower().removeprefix("www.")
        t["host"] = host
        parts = s.split("/")
        if host != "github.com":
            cut = next((i for i, x in enumerate(parts) if x in ("-", "blob", "tree")), len(parts))
            t["repo"] = "/".join(parts[:cut]) if cut >= 2 else None  # keeps GitLab nested groups
            continue
        if len(parts) >= 2:
            t["repo"] = f"{parts[0]}/{parts[1]}"
        if len(parts) >= 5 and parts[2] == "blob":
            rest, _, frag = "/".join(parts[3:]).partition("#")
            # The ref may contain slashes (feature/x); collect_github resolves the split.
            t["snippet"] = {"ref_and_path": rest, "lines": frag}
    if not t["repo"] and not t["package"]:
        t["error"] = "could not parse target: use owner/repo, a GitHub URL, eco:name or repo+eco:name"
    return t


# ---------------------------------------------------------------- collectors
def collect_package(eco: str, name: str) -> dict:
    out: dict = {"ecosystem": eco, "name": name, "notes": []}
    if eco not in ECO:
        out["notes"].append(f"unknown ecosystem '{eco}'")
        return out
    registry, osv_eco = ECO[eco]
    st, _, d = http(f"https://packages.ecosyste.ms/api/v1/registries/{registry}/packages/{q(name)}")
    if st == 404:
        out["not_found"] = True
        return out
    if st != 200 or not isinstance(d, dict):
        out["notes"].append(f"ecosyste.ms package lookup failed ({st})")
        return out
    for k in ("downloads", "downloads_period", "dependent_repos_count", "dependent_packages_count",
              "first_release_published_at", "latest_release_published_at", "latest_release_number",
              "repository_url", "normalized_licenses", "status"):
        out[k] = d.get(k)
    out["maintainers_count"] = len(d.get("maintainers") or [])
    version = d.get("latest_release_number")
    if osv_eco and version:
        st, _, v = http("https://api.osv.dev/v1/query",
                        data={"package": {"name": name, "ecosystem": osv_eco}, "version": version})
        if st == 200 and isinstance(v, dict):
            vulns = []
            for item in v.get("vulns", []) or []:
                sev = (item.get("database_specific") or {}).get("severity") or "UNKNOWN"
                vulns.append({"id": item.get("id"), "severity": str(sev).upper(),
                              "summary": (item.get("summary") or "")[:100]})
            out["vulns_on_latest"] = vulns
        else:
            out["notes"].append(f"OSV query failed ({st})")
    if eco == "npm":
        st, _, meta = http(f"https://registry.npmjs.org/{q(name)}/latest")
        if st == 200 and isinstance(meta, dict):
            scripts = meta.get("scripts") or {}
            out["install_scripts"] = {k: v for k, v in scripts.items()
                                      if k in ("preinstall", "install", "postinstall")}
    return out


def collect_github(repo: str, snippet: dict | None) -> dict:
    out: dict = {"notes": [], "failed": []}
    st, _, r = gh(f"repos/{repo}")
    if st == 404:
        out["not_found"] = True
        out["notes"].append("GitHub repo not found (private, deleted, or wrong name)")
        return out
    if st != 200 or not isinstance(r, dict):
        out["failed"].append(f"repo ({st or 'network error'})")
        return out

    def fetch(path: str, label: str):
        """GET that records non-404 failures so partial data is never silently scored."""
        st, h, d = gh(path)
        if st not in (200, 404):
            out["failed"].append(f"{label} ({st or 'network error'})")
        return st, h, d
    branch = r.get("default_branch") or "main"
    out["repo"] = {k: r.get(k) for k in ("full_name", "description", "created_at", "pushed_at", "archived",
                                          "fork", "stargazers_count", "forks_count", "subscribers_count",
                                          "open_issues_count", "has_issues", "homepage", "topics")}
    out["repo"]["license"] = (r.get("license") or {}).get("spdx_id")
    out["repo"]["owner_type"] = (r.get("owner") or {}).get("type")
    out["repo"]["parent"] = (r.get("parent") or {}).get("full_name")
    out["repo"]["default_branch"] = branch
    owner = (r.get("owner") or {}).get("login")

    def owner_info():
        if out["repo"]["owner_type"] != "User":
            return None
        st, _, u = fetch(f"users/{owner}", "owner")
        return {k: u.get(k) for k in ("created_at", "followers", "public_repos")} if st == 200 else None

    def tree():
        st, _, t = fetch(f"repos/{repo}/git/trees/{q(branch)}?recursive=1", "tree")
        if st != 200 or not isinstance(t, dict):
            return None
        return {"paths": [e["path"] + ("/" if e.get("type") == "tree" else "") for e in t.get("tree", [])],
                "truncated": t.get("truncated")}

    def readme():
        st, _, d = fetch(f"repos/{repo}/readme", "readme")
        if st == 200 and isinstance(d, dict) and d.get("content"):
            return base64.b64decode(d["content"]).decode("utf-8", "replace")
        return None

    def commits():
        st, _, c = fetch(f"repos/{repo}/commits?per_page=100", "commits")
        return c if st == 200 and isinstance(c, list) else []

    def first_commit():
        st, h, one = fetch(f"repos/{repo}/commits?per_page=1", "commit count")
        total = (last_page(h) or (1 if one else None)) if st == 200 else None
        if not total:
            return {"total_commits": total}
        st, _, c = gh(f"repos/{repo}/commits?per_page=1&page={total}")
        if st != 200 or not c:
            return {"total_commits": total}
        sha = c[0]["sha"]
        st, _, full = gh(f"repos/{repo}/commits/{sha}")
        stats = (full or {}).get("stats", {}) if st == 200 else {}
        return {"total_commits": total, "first_commit_date": c[0]["commit"]["author"]["date"],
                "first_commit_additions": stats.get("additions"),
                "first_commit_files": len((full or {}).get("files") or []) if st == 200 else None}

    def contributors():
        st, h, c = fetch(f"repos/{repo}/contributors?per_page=1&anon=1", "contributors")
        if st != 200:
            return None
        return last_page(h) or (len(c) if isinstance(c, list) else 0)

    def pulls():
        # One GraphQL call: ~4 KB instead of ~0.5-1 MB of REST PR objects plus two
        # search calls, and no exposure to the 30/min search budget.
        o, n = repo.split("/", 1)
        st, _, d = gql(PR_QUERY, {"owner": o, "name": n})
        r = ((d or {}).get("data") or {}).get("repository") if st == 200 and isinstance(d, dict) else None
        if not r:
            out["failed"].append("PR review signals (GraphQL needs a token)" if not TOKEN
                                 else f"PR review signals ({st or 'network error'})")
            return None
        return {"total_merged": r["merged"]["totalCount"], "recent": r["recent"]["nodes"]}

    def issues():
        st, _, i = fetch(f"repos/{repo}/issues?state=all&per_page=50", "issues")
        return [x for x in i if "pull_request" not in x] if st == 200 and isinstance(i, list) else []

    def releases():
        st, _, rel = fetch(f"repos/{repo}/releases?per_page=10", "releases")
        if st == 200 and isinstance(rel, list) and rel:
            return rel
        st, _, tags = fetch(f"repos/{repo}/tags?per_page=10", "tags")  # tag-only release process
        return [{"tag_name": x.get("name"), "published_at": None, "body": "", "tag_only": True}
                for x in tags] if st == 200 and isinstance(tags, list) else []

    def runs():
        st, _, d = fetch(f"repos/{repo}/actions/runs?branch={q(branch)}&per_page=10", "ci runs")
        return d.get("workflow_runs", []) if st == 200 and isinstance(d, dict) else []

    def scorecard():
        st, _, d = http(f"https://api.securityscorecards.dev/projects/github.com/{repo}")
        if st == 200 and isinstance(d, dict):
            return {"score": d.get("score"), "date": d.get("date"),
                    "checks": {c["name"]: c.get("score") for c in d.get("checks", [])}}
        return None

    def eco_commits():
        st, _, d = http(f"https://commits.ecosyste.ms/api/v1/hosts/GitHub/repositories/{repo}")
        if st == 200 and isinstance(d, dict):
            return {k: d.get(k) for k in ("total_committers", "dds", "past_year_total_commits",
                                          "past_year_total_committers", "past_year_dds")}
        return None

    def snippet_info():
        if not snippet:
            return None
        segs = snippet["ref_and_path"].split("/")
        sha, ref, path = None, segs[0], "/".join(segs[1:])
        for i in range(1, min(len(segs), 5)):  # branch names may contain '/'
            st, _, c = gh(f"repos/{repo}/commits/{q('/'.join(segs[:i]))}")
            if st == 200 and isinstance(c, dict):
                sha, ref, path = c.get("sha"), "/".join(segs[:i]), "/".join(segs[i:])
                break
        snippet.update(ref=ref, path=path)
        st, _, hist = gh(f"repos/{repo}/commits?path={q(path)}&sha={q(ref)}&per_page=20")
        hist = hist if st == 200 and isinstance(hist, list) else []
        frag = f"#{snippet['lines']}" if snippet.get("lines") else ""
        return {"path": snippet["path"], "pinned_sha": sha,
                "permalink": f"https://github.com/{repo}/blob/{sha}/{snippet['path']}{frag}" if sha else None,
                "file_last_changed": hist[0]["commit"]["author"]["date"] if hist else None,
                "file_distinct_authors": len({(h.get("author") or {}).get("login") or h["commit"]["author"]["name"]
                                              for h in hist})}

    jobs = {"owner": owner_info, "tree": tree, "readme": readme, "commits": commits, "first": first_commit,
            "contributors": contributors, "pulls": pulls, "issues": issues, "releases": releases,
            "runs": runs, "scorecard": scorecard, "eco_commits": eco_commits, "snippet": snippet_info}
    with ThreadPoolExecutor(max_workers=8) as pool:
        futures = {k: pool.submit(f) for k, f in jobs.items()}
        for k, f in futures.items():
            try:
                out[k] = f.result()
            except Exception as e:  # one broken source must not hide the others
                out[k] = None
                out["notes"].append(f"{k}: {type(e).__name__}: {e}")
    if out.get("tree") and out["tree"].get("truncated"):
        out["notes"].append("git tree truncated (huge repo): file-based ratios are approximate")
    return out


