    if young:
        crit_a = {
            "organization or ≥3 significant humans": repo.get("owner_type") == "Organization" or sig_humans >= 3,
            "review culture (≥30% approved or ≥3 external PRs)": (approved_ratio or 0) >= 0.3 or len(ext_merged) >= 3,
            "CI present and mostly green": has_ci and (ci_success is None or ci_success >= 0.7),
            "tests (ratio ≥0.1)": (test_ratio or 0) >= 0.1,
            "≥3 versioned releases": len(releases) >= 3,
            "active (push ≤60d)": since_push is not None and since_push <= 60,
            "external users filing issues (≥5/50)": len(ext_issues) >= 5,
            "no strong vibe tells": score < 3,
        }
        need_b = 5
    else:
        crit_a = {
            "age ≥3y": age is not None and age >= 3 * 365,
            "active (push ≤365d)": since_push is not None and since_push <= 365,
            "≥10 contributors": ((g or {}).get("contributors") or 0) >= 10,
            "strong adoption (dependents/downloads)": adoption_a,
            "Scorecard ≥6 (or unavailable)": sc.get("score") is None or sc["score"] >= 6,
            "no strong vibe tells": score < 3,
        }
        crit_b = [age is not None and age >= 365, since_push is not None and since_push <= 365,
                  ((g or {}).get("contributors") or 0) >= 3, adoption_b, has_ci]
    unmet = [k for k, ok in crit_a.items() if not ok]
    if gates or vibe.startswith("LIKELY"):
        tier = "D"
    elif vibe.startswith("SUSPECT"):
        tier = "C (capped by SUSPECT vibe verdict: clear it with the 5-minute read)"
    elif failed:
        tier = "? (data incomplete: rerun)"
    elif not unmet:
        tier = "A" + (" (young-field: also needs one named backing anchor)" if young else "")
    elif (young and sum(crit_a.values()) >= need_b) or (not young and all(crit_b)):
        tier = "B"
    else:
        tier = "C"

    return {"target": t["raw"], "repo": repo.get("full_name") or t.get("repo"), "track": "young-field" if young else "established",
            "metric_tier": tier, "unmet_for_A": unmet, "gates": gates, "flags": flags,
            "vibe_verdict": vibe, "vibe_score": score, "vibe_tells": [f"[{w}] {s}" for w, s in tells],
            "green": green, "facts": facts,
            "notes": ((g or {}).get("notes") or []) + ((pkg or {}).get("notes") or [])}


