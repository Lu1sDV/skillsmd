def collect_repo(t: dict) -> dict | None:
    if t["repo"] and t["host"] == "github.com":
        return collect_github(t["repo"], t["snippet"])
    if not t["repo"]:
        return None
    st, _, d = http(f"https://repos.ecosyste.ms/api/v1/hosts/{q(t['host'])}/repositories/{q(t['repo'])}")
    g = {"notes": [f"non-GitHub host {t['host']}: partial metadata from ecosyste.ms only; "
                   "verify license, activity and review culture by hand"]}
    if st == 200 and isinstance(d, dict):
        g["repo"] = {"full_name": d.get("full_name"), "created_at": d.get("created_at"),
                     "pushed_at": d.get("pushed_at"), "archived": d.get("archived"),
                     "stargazers_count": d.get("stargazers_count"), "forks_count": d.get("forks_count"),
                     "license": SPDX_CASE.get((d.get("license") or "").lower(), d.get("license")),
                     "owner_type": None}
    return g


def run(raw: str, young: bool) -> dict:
    try:
        return _run(raw, young)
    except Exception as e:  # one bad target must not lose the whole shortlist
        return {"target": raw, "error": f"{type(e).__name__}: {e}"}


def _run(raw: str, young: bool) -> dict:
    t = parse_target(raw)
    if t["error"]:
        return {"target": raw, "error": t["error"]}
    if t["repo"] and t["package"]:
        # Independent sources: overlap the registry/OSV chain with GitHub collection.
        with ThreadPoolExecutor(max_workers=1) as pool:
            fut = pool.submit(collect_package, *t["package"])
            g = collect_repo(t)
            pkg = fut.result()
        return analyse(t, g, pkg, young)
    pkg = collect_package(*t["package"]) if t["package"] else None
    if not t["repo"] and pkg and pkg.get("repository_url"):
        m = re.search(r"github\.com[/:]([^/]+)/([^/#?]+)", pkg["repository_url"])
        if m:
            t["repo"] = f"{m.group(1)}/{re.sub(r'[.]git$', '', m.group(2))}"
            t["host"] = "github.com"
    return analyse(t, collect_repo(t), pkg, young)


def collect_all(targets: list[str], young: bool) -> list[dict]:
    """Targets are independent network-bound jobs; results keep input order."""
    if len(targets) == 1:
        return [run(targets[0], young)]
    with ThreadPoolExecutor(max_workers=min(TARGET_WORKERS, len(targets))) as pool:
        return list(pool.map(lambda x: run(x, young), targets))


def render(r: dict) -> str:
    if r.get("error"):
        return f"== {r['target']}\nERROR: {r['error']}"
    f = r["facts"]
    L = [f"== {r['repo'] or r['target']}   track: {r['track']}",
         f"Metric tier: {r['metric_tier']}   (mechanical: apply authority override/demotion with named evidence)"]
    if r["unmet_for_A"]:
        L.append(f"  unmet for A: {'; '.join(r['unmet_for_A'])}")
    L.append(f"Gates: {'; '.join(r['gates']) or 'none'}")
    for x in r["flags"]:
        L.append(f"Flag: {x}")
    L.append(f"Vibe check: {r['vibe_verdict']}  (score {r['vibe_score']}, green {len(r['green'])})")
    L += [f"  tell {x}" for x in r["vibe_tells"]]
    L += [f"  green {x}" for x in r["green"]]
    L.append("Facts:")
    for k, v in f.items():
        if v not in (None, [], {}, ""):
            L.append(f"  {k}: {v}")
    for n in r["notes"]:
        L.append(f"Note: {n}")
    if not TOKEN:
        L.append("Note: no GitHub token (60 req/h unauthenticated); run `gh auth login` or set GITHUB_TOKEN")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("targets", nargs="+")
    ap.add_argument("--young-field", action="store_true",
                    help="judge on organisation/engineering discipline instead of age/adoption (auto if repo < 2y)")
    ap.add_argument("--json", action="store_true", help="emit full JSON")
    a = ap.parse_args()
    results = collect_all(a.targets, a.young_field)
    if a.json:
        print(json.dumps(results, indent=2, default=str))
    else:
        print("\n\n".join(render(r) for r in results))
    return 0


if __name__ == "__main__":
    sys.exit(main())
