def is_bot(login: str | None, name: str = "", typ: str | None = None) -> bool:
    s = f"{login or ''} {name}".lower()
    return (typ == "Bot" or "[bot]" in s or s.strip() in {"dependabot", "renovate", "github-actions", "copilot"})


def user_is_bot(u: dict | None) -> bool:
    u = u or {}
    return is_bot(u.get("login"), "", u.get("type") or u.get("__typename"))


MAINT_BOT = re.compile(r"^(dependabot|renovate|pre-commit-ci|github-actions|mergify|allcontributors|"
                       r"release-please|snyk-bot|greenkeeper|imgbot|depfu)", re.I)
CODING_BOT = re.compile(r"copilot|devin|jules|codex|openhands|lovable|gpt-engineer|^v0|cursor|claude|"
                        r"sweep|aider", re.I)


FIXTURE_PATH = re.compile(r"(^|/)(tests?|__tests__|spec|fixtures?|testdata|test-data|examples?|samples?|"
                          r"e2e|benchmarks?)/", re.I)


def committed_dependency_dirs(paths: list[str]) -> list[str]:
    """Evidence-based: a module named venv (CPython's Lib/venv) is not a committed virtualenv."""
    real = [p for p in paths if not FIXTURE_PATH.search(p)]
    found = []
    if sum("node_modules/" in p for p in real) >= 20:
        found.append("node_modules")
    if any(p.endswith("pyvenv.cfg") for p in real):
        found.append("virtualenv (pyvenv.cfg)")
    if sum("site-packages/" in p for p in real) >= 20:
        found.append("site-packages")
    if sum(p.endswith(".pyc") for p in real) >= 5:
        found.append("*.pyc")
    return found


def variant_files(code_files: list[str]) -> list[str]:
    """foo_fixed.py / enhanced_foo.py next to foo.py (any code ext, same dir)."""
    stems = {(p.rsplit("/", 1)[0] if "/" in p else "", p.rsplit("/", 1)[-1].rsplit(".", 1)[0].lower())
             for p in code_files}
    hits = []
    for p in code_files:
        if TEST_PATH.search(p):
            continue
        d = p.rsplit("/", 1)[0] if "/" in p else ""
        stem = p.rsplit("/", 1)[-1].rsplit(".", 1)[0]
        m, mp = VARIANT_SUFFIX.search(stem), VARIANT_PREFIX.match(stem)
        base = stem[:m.start()] if m else stem[mp.end():] if mp else None
        if base is None:
            continue
        if base and (d, base.lower()) in stems:
            hits.append(p)
    return hits


